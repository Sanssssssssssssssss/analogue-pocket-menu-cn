"""Give the shared compositor five associative physical cover slots.

The accepted geometry, shading, title and raster code are still generated by
prepare_view. This separate adapter does not change the GBA build inputs.
"""
import argparse,json,shutil
from pathlib import Path
from prepare_view import prepare,ROOT,HERE,take


def adapt(text):
    text=text.replace('module coverflow_view #(parameter CB=7,','module coverflow_assoc_view #(parameter CB=3,',1)
    text=text.replace('input wire [10:0] cache_game,idx,count,',
        'input wire [10:0] cache_game,idx,count,\n    input wire [2:0] cache_slot,\n    output wire [2:0] wanted_slot,',1)
    start=text.index('// ---------------------------------------------------------------- cover cache (clk_74a)')
    end=text.index('// position bar thumb:',start)
    old=text[start:end]
    # Keep the original candidate/wrap calculation and neighbor priority.
    candidates=take(old,'// candidate offsets:','wire [10:0] tg_now =')
    replacement='''wire [10:0] cg[0:3];
wire cl[0:3];wire [2:0] physical[0:3];
'''+candidates+'''
always @(posedge clk_74a)if(ago)last_left<=ago_dir;
wire assoc_keys_valid=c_valid && idx==c_idx && rcount==c_cnt && last_left==c_left && rlo==c_lo;
coverflow_assoc_cache assoc(.clk(clk_74a),.enable(enable),.invalidate(invalidate),.keys_valid(assoc_keys_valid),
    .candidates(neighbors),.visible(cg),.commit(cache_commit),.commit_slot(cache_slot),.commit_game(cache_game),
    .want(want_art),.wanted_game(wanted_game),.wanted_slot(wanted_slot),.loaded(cl),.physical(physical));
'''
    text=text[:start]+replacement+text[end:]
    before='vg[vk] <= cg[vk][CB-1:0];'
    if text.count(before)!=1:raise ValueError('Visible slot mapping anchor changed')
    return text.replace(before,'vg[vk] <= physical[vk];')


def build(out):
    out=prepare(out,compact=True)
    path=out/'coverflow_view.sv'
    (out/'coverflow_assoc_view.sv').write_text(adapt(path.read_text(encoding='utf8')),encoding='utf8',newline='\n')
    shutil.copy2(HERE/'assoc_cache.sv',out/'coverflow_assoc_cache.sv')
    proof=json.loads((out/'view-source.json').read_text())
    proof['cache_adapter']='Five physical slots; original candidate wrap/priority and raster, fully associative tags'
    (out/'view-source.json').write_text(json.dumps(proof,indent=2)+'\n')
    return out


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',required=True);a=p.parse_args();print(build(a.out))
